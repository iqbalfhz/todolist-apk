/// Ubin peta untuk tes: PNG transparan 1 × 1, jadi tidak ada yang diunduh dari OpenStreetMap.
class FakeTileProvider extends TileProvider {
  FakeTileProvider();

  /// Ubin yang diminta, untuk memastikan peta benar-benar ditampilkan.
  final List<TileCoordinates> requested = [];

  @override
  ImageProvider getImage(TileCoordinates coordinates, TileLayer options) {
    requested.add(coordinates);
    return MemoryImage(transparentPng);
  }
}

